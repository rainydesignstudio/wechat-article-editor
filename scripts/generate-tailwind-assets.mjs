import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const themeCss = read('node_modules/tailwindcss/theme.css');
const utilitiesCss = read('node_modules/tailwindcss/utilities.css');

fs.writeFileSync(
  path.join(root, 'src/lib/tailwind-assets.ts'),
  `// Generated by scripts/generate-tailwind-assets.mjs.\nexport const TAILWIND_THEME_CSS = ${JSON.stringify(themeCss)};\nexport const TAILWIND_UTILITIES_CSS = ${JSON.stringify(utilitiesCss)};\n`,
);
