import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const root = process.cwd();
function compile(file) {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  return ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext } }).outputText
    .replace(/^export (?=function|async function)/gm, '');
}
const output = `// Generated by scripts/generate-format-assets.mjs from the shared TypeScript sources.\n(() => {\n${compile('src/lib/article-format/colors.ts')}\nwindow.ArticleColorNormalizer = createArticleColorNormalizer;\n${compile('src/lib/article-format/bootstrap.ts')}\nvoid runFormatFrameBootstrap();\n})();\n`;
const target = path.join(root, 'public/article-format-bootstrap.js');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) fs.writeFileSync(target, output);
